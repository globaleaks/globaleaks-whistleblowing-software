DEMO_PASSWORD = 'demo-password'


def _seed_field_answer(field, report_number):
    field_type = field['type']
    label = field.get('label', '')
    if isinstance(label, dict):
        label = label.get('en', '')
    if field_type == 'selectbox':
        option_index = report_number % len(field['options']) if field['options'] else 0
        value = {'value': field['options'][option_index]['id']} \
            if field['options'] else {'value': ''}
    elif field_type == 'fileupload':
        value = {}
    elif 'summarize' in label.lower():
        value = {'value': f'Procurement irregularity report {report_number}'}
    elif 'evidence in detail' in label.lower():
        value = {'value': 'Attached invoice and approval records support the reported discrepancy.'}
    elif 'detail' in label.lower():
        value = {'value': f'Invoices show repeated overbilling in contract {report_number:05d}. '
                          'The payments were approved despite the documented price differences.'}
    elif 'where' in label.lower():
        value = {'value': f'Regional office {report_number % 12 + 1}, Building {report_number % 20 + 1}'}
    elif 'when' in label.lower():
        value = {'value': f'{2020 + report_number % 7}-0{report_number % 9 + 1}-15'}
    elif 'list the organizations' in label.lower():
        value = {'value': 'Internal Audit Department; no investigation outcome has been communicated.'}
    elif 'investigated' in label.lower():
        value = {'value': 'The review is still ongoing.'}
    elif 'outcome you want' in label.lower():
        value = {'value': 'Please investigate the contract and recover any improperly paid funds.'}
    else:
        value = {'value': f'Demo report {report_number}: suspected procurement irregularity. '
                          f'Estimated impact: {(report_number % 97) + 1} units.'}
    return value


def _write_demo_file(file_id, content):
    path = os.path.join(Settings.attachments_path, file_id)
    with open(path, 'wb') as attachment:
        attachment.write(content)


def _add_report_attachment(session, tid, report, number, file_field_id):
    fixture_dir = os.path.abspath(os.path.join(Settings.src_path, '..', 'client',
                                               'cypress', 'fixtures', 'files'))
    fixture_name = 'test.zip' if number % 1000 == 0 else 'test.pdf' if number % 10 == 0 else 'test.txt'
    fixture_path = os.path.join(fixture_dir, fixture_name)
    if os.path.isfile(fixture_path):
        with open(fixture_path, 'rb') as fixture:
            content = fixture.read()
        content_type = mimetypes.guess_type(fixture_path)[0] or 'application/octet-stream'
    else:
        content = (f'Evidence file for demo report {number}.\n'
                   'Generated by GlobaLeaks seeding mode.\n').encode()
        fixture_name = 'evidence.txt'
        content_type = 'text/plain'
    file_id = uuid4()
    name = f'report-{number:06d}-{fixture_name}'
    _write_demo_file(file_id, content)

    attachment = models.InternalFile()
    attachment.tid = tid
    attachment.id = file_id
    attachment.internaltip_id = report.id
    attachment.name = name
    attachment.content_type = content_type
    attachment.size = len(content)
    attachment.reference_id = f'{file_field_id}-0'
    attachment.hash_sha256 = sha256(content).decode()
    attachment.hash_sha512 = sha512(content).decode()
    attachment.state = 'verified'
    attachment.verification_date = datetime_now()
    session.add(attachment)


def _add_recipient_activity(session, report, receiver_id, number):
    now = datetime_now()
    content = f'Review note for demo report {number}: please verify the supporting documents.'

    comment = models.Comment()
    comment.internaltip_id = report.id
    comment.author_id = receiver_id
    comment.content = content
    comment.visibility = 'personal' if number % 4 == 0 else 'public'
    comment.new = False
    comment.hash_sha256 = sha256(content).decode()
    comment.hash_sha512 = sha512(content).decode()
    comment.creation_date = report.update_date
    session.add(comment)

    if number % 20 == 0:
        attachment_content = f'Recipient response for demo report {number}.\n'.encode()
        file_id = uuid4()
        name = f'recipient-response-{number:06d}.txt'
        _write_demo_file(file_id, attachment_content)

        recipient_file = models.ReceiverFile()
        recipient_file.id = file_id
        recipient_file.internaltip_id = report.id
        recipient_file.author_id = receiver_id
        recipient_file.name = name
        recipient_file.size = len(attachment_content)
        recipient_file.content_type = 'text/plain'
        recipient_file.description = 'Generated demo response attachment'
        recipient_file.visibility = 'public' if number % 40 == 0 else 'personal'
        recipient_file.new = False
        recipient_file.hash_sha256 = sha256(attachment_content).decode()
        recipient_file.hash_sha512 = sha512(attachment_content).decode()
        recipient_file.state = 'verified'
        recipient_file.verification_date = now
        session.add(recipient_file)


def _wizard_request(tenant_name, receipt_salt):
    return {
        'node_language': 'en',
        'node_name': tenant_name,
        'admin_username': 'admin',
        'admin_name': 'Demo Administrator',
        'admin_password': GCE.derive_key(
            DEMO_PASSWORD, GCE.generate_salt(f'{receipt_salt}:admin')
        ),
        'admin_mail_address': '',
        'admin_escrow': False,
        'receiver_username': 'recipient',
        'receiver_name': 'Demo Recipient',
        'receiver_password': GCE.derive_key(
            DEMO_PASSWORD, GCE.generate_salt(f'{receipt_salt}:recipient')
        ),
        'receiver_mail_address': '',
        'profile': 'default',
        'skip_admin_account_creation': False,
        'skip_recipient_account_creation': False,
        'enable_developers_exception_notification': False,
    }


@transact_sync
def _seed_tenants(session, tenant_count):
    tenant_data = []
    for tid in range(1, tenant_count + 1):
        if tid > 1:
            tenant.db_create(session, {
                'active': True,
                'profile': 'default',
                'name': f'Demo Tenant {tid:05d}',
                'subdomain': f'demo-{tid:05d}',
            })

        receipt_salt = ConfigFactory(session, tid).get_val('receipt_salt')
        tenant.db_wizard(session, tid, '',
                         _wizard_request(f'Demo Tenant {tid:05d}', receipt_salt))
        # Seeded reports are generated without whistleblower key pairs; keep
        # encryption and support keys disabled for every seeded tenant so
        # demo users can log in without generating personal private keys.
        db_set_config_variable(session, tid, 'encryption', False)
        db_set_config_variable(session, tid, 'crypto_support_pub_key', '')
        db_set_config_variable(session, tid, 'demo', True)
        # Seeded accounts deliberately have no email addresses. Disable both
        # notification generation and SMTP delivery for this demo tenant.
        for setting in (
            'enable_admin_notification_emails',
            'enable_analyst_notification_emails',
            'enable_custodian_notification_emails',
            'enable_receiver_notification_emails',
            'smtp_enabled',
            'smtp2_enabled',
        ):
            db_set_config_variable(session, tid, setting, False)

        receiver = session.query(models.User).filter_by(tid=tid, username='recipient').one()
        session.query(models.User).filter_by(tid=tid).update(
            {models.User.password_change_needed: False}, synchronize_session=False
        )
        context = session.query(models.Context).filter_by(tid=tid).first()
        if context is None:
            raise RuntimeError(f'Seeding failed: tenant {tid} has no default context')

        session.flush()
        questionnaire = session.query(models.Questionnaire).filter_by(id=context.questionnaire_id).one()
        schema = serialize_questionnaire(session, tid, questionnaire, None)
        file_field_id = next(
            field['id'] for step in schema['steps'] for field in step['children']
            if field['type'] == 'fileupload'
        )
        tenant_data.append((tid, receiver.id, context.id, context.questionnaire_id, file_field_id))
    return tenant_data


@transact_sync
def _seed_reports(session, tenant_data, submissions_per_tenant):
    from globaleaks.handlers.whistleblower.submission import db_archive_questionnaire_schema, db_set_internaltip_answers

    for tid, receiver_id, context_id, questionnaire_id, file_field_id in tenant_data:
        questionnaire = session.query(models.Questionnaire).filter_by(id=questionnaire_id).one()
        schema = serialize_questionnaire(session, tid, questionnaire, None)
        schema_hash = db_archive_questionnaire_schema(session, schema['steps'])

        for number in range(1, submissions_per_tenant + 1):
            answers = {}
            for step in schema['steps']:
                for field in step['children']:
                    answers[field['id']] = [_seed_field_answer(field, number)]
            receipt = f'{number:016d}'
            report = models.InternalTip()
            report.id = uuid4()
            report.tid = tid
            report.context_id = context_id
            report.status = ('new', 'opened', 'closed')[number % 3]
            report.progressive = number
            report.creation_date = datetime_now() - timedelta(days=number % 365)
            report.update_date = report.creation_date
            report.last_access = report.creation_date
            report.tor = number % 7 == 0
            report.mobile = number % 5 == 0
            report.important = number % 11 == 0
            report.label = f'Demo priority {number % 5}' if number % 11 == 0 else ''
            salt = ConfigFactory(session, tid).get_val('receipt_salt')
            _, receipt_hash = GCE.calculate_key_and_hash(receipt, salt)
            report.receipt_hash = receipt_hash
            session.add(report)

            db_set_internaltip_answers(session, report.id, questionnaire_id,
                                       schema_hash, answers, {})
            receiver_tip = models.ReceiverTip()
            receiver_tip.internaltip_id = report.id
            receiver_tip.receiver_id = receiver_id
            receiver_tip.new = False
            if report.status == 'opened':
                receiver_tip.access_date = report.creation_date
                receiver_tip.last_access = report.creation_date
            session.add(receiver_tip)

            if number == 1 or number % 5 == 0:
                _add_report_attachment(session, tid, report, number, file_field_id)
            if number % 5 == 0:
                _add_recipient_activity(session, report, receiver_id, number)

        ConfigFactory(session, tid).set_val('counter_submissions', submissions_per_tenant)


def seed_database(tenant_count, submissions_per_tenant):
    """Populate an initialized, empty database before the API starts listening."""
    session = get_session()
    try:
        if session.query(models.User.id).first() or \
                session.query(models.InternalTip.id).first() or \
                session.query(models.Context.id).filter(models.Context.tid != 1000001).first():
            raise RuntimeError('Seeding refused: database already contains application data')
    finally:
        session.close()

    log.err('WARNING: DATABASE SEEDING MODE ENABLED. This instance uses guessable demo receipts and credentials.')
    log.err('WARNING: Do not expose this seeded instance to production users.')
    tenant_data = _seed_tenants(tenant_count)
    _seed_reports(tenant_data, submissions_per_tenant)
    log.err('Seeded %d tenants with %d reports each. Demo login: admin/recipient with password %s',
            tenant_count, submissions_per_tenant, DEMO_PASSWORD)
